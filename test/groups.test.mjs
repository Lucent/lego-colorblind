/* Full pipeline test over the real Rebrickable color table:
   simulate CVD → Lab → union-find grouping. Requires cache/colors.json
   (generated by the server's refresh on first boot). */
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { simulate } from "../public/client/simulate.mjs";
import { labFromSrgb } from "../public/client/color.mjs";
import { similarGroups } from "../public/client/groups.mjs";

const colors = JSON.parse(await readFile(new URL("../cache/colors.json", import.meta.url)));
for (const c of Object.values(colors)) {
	c.rgb = [1, 3, 5].map(i => parseInt(c.rgb.slice(i - 1, i + 1), 16));
	if (c.trans) c.rgb = c.rgb.map(v => 255 + (v - 255) * 0.5);
}

const isTrans = id => colors[id]?.trans ?? false;

function groupsFor(ids, type, severity, darken = 0) {
	const labs = new Map(ids.map(id => {
		const lab = labFromSrgb(simulate(type, severity, colors[id].rgb));
		lab[0] = Math.max(0, lab[0] - darken);
		return [id, lab];
	}));
	return similarGroups(ids, labs, isTrans);
}

// Dark Green(288), Reddish Brown(70), Blue(1), White(15), Trans-Red(36)
const sample = ["288", "70", "1", "15", "36"];

test("normal vision finds these distinct colors distinct", () => {
	assert.equal(groupsFor(sample, "normal", 1).length, 0);
});

test("deuteranopia confuses Dark Green with Reddish Brown", () => {
	// the reference pair the original PHP threshold was tuned around
	const groups = groupsFor(sample, "deutan", 1);
	assert.equal(groups.length, 1);
	assert.deepEqual(groups[0].members.map(m => sample[m]).sort(), ["288", "70"].sort());
});

test("trans colors never group with solids, even identical ones", () => {
	// Trans-Red(36) composited is lighter than Red(4), but force worst case:
	// full achromatopsia in dim light collapses nearly everything
	for (const g of groupsFor(sample, "achromat", 1, 50)) {
		const kinds = new Set(g.members.map(m => isTrans(sample[m])));
		assert.equal(kinds.size, 1);
	}
});

test("severity slider is live: 0 groups nothing, 1 groups the most", () => {
	assert.equal(groupsFor(sample, "deutan", 0).length, 0);
	const counts = [0.25, 0.5, 1].map(s =>
		groupsFor(sample, "deutan", s).flatMap(g => g.members).length);
	assert.ok(counts[2] >= counts[1] && counts[1] >= counts[0], `${counts}`);
});

test("dim lighting makes dark colors harder to tell apart", () => {
	// Black(0) vs Dark Blue(272): ΔE 15.7 lit, 11.6 dimmed
	const pair = ["0", "272"];
	assert.equal(groupsFor(pair, "normal", 1, 0).length, 0);
	assert.equal(groupsFor(pair, "normal", 1, 50).length, 1);
});

test("identical color ids always group (same-mold duplicates)", () => {
	assert.equal(groupsFor(["4", "4"], "normal", 1).length, 1);
});

test("all 275 colors × all types × 5 severities runs fast (realtime budget)", () => {
	const all = Object.keys(colors);
	const t0 = performance.now();
	for (const type of ["protan", "deutan", "tritan", "achromat"])
		for (const s of [0.2, 0.4, 0.6, 0.8, 1])
			groupsFor(all, type, s);
	const ms = performance.now() - t0;
	// 275 colors is ~10x a big set's distinct colors; a slider tick does 1/20 of this
	assert.ok(ms < 2000, `${ms}ms`);
});
